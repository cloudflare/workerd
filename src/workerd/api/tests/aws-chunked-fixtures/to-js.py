"""Writes captured aws-chunked uploads as the JavaScript fixture module.

Usage: to-js.py CAPTURES_JSON > aws-chunked-sdk-fixtures.js

Each body is stored as its framing, verbatim, with the payload runs between replaced by their
lengths. The payload is the same sentence repeated, which the test regenerates. The script checks
that every fixture rebuilds its captured body byte for byte.
"""

import base64
import json
import re
import sys
from pathlib import Path

SENTENCE = b"The quick brown fox jumps over the lazy dog. "


def payload(n):
    return (SENTENCE * (n // len(SENTENCE) + 2))[:n]


def split(body):
    """Splits `body` into framing (bytes) and payload lengths (ints)."""
    parts, i = [b""], 0
    while True:
        end = body.index(b"\r\n", i) + 2
        line = body[i:end]
        parts[-1] += line
        size = int(line.split(b";")[0].strip(), 16)
        i = end
        if size == 0:
            parts[-1] += body[i:]
            return parts
        i += size
        assert body[i : i + 2] == b"\r\n"
        parts += [size, b"\r\n"]
        i += 2


def rebuild(parts, decoded_length):
    data = payload(decoded_length)
    out, offset = b"", 0
    for part in parts:
        if isinstance(part, int):
            out += data[offset : offset + part]
            offset += part
        else:
            out += part
    assert offset == decoded_length
    return out


def client(user_agent):
    names = []
    for pattern in [
        r"aws-sdk-js/\S+",
        r"Boto3/\S+",
        r"aws-sdk-go-v2/\S+",
        r"api/s3#\S+",
        r"minio-go/\S+",
    ]:
        names += re.findall(pattern, user_agent)
    return " ".join(names)


def js_string(data):
    text = data.decode("ascii")
    return (
        "'"
        + text.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        + "'"
    )


def main():
    captures = json.loads(Path(sys.argv[1]).read_text())
    names = sorted(captures)
    print("// Copyright (c) 2026 Cloudflare, Inc.")
    print("// Licensed under the Apache 2.0 license found in the LICENSE file or at:")
    print("//     https://opensource.org/licenses/Apache-2.0")
    print()
    print("// Generated by aws-chunked-fixtures/to-js.py from the uploads described in")
    print("// aws-chunked-fixtures/README.md. Do not edit.")
    print("//")
    print(
        "// Each body is the request body a client sent, with its framing verbatim and each run of payload"
    )
    print(
        "// bytes replaced by its length. The payload is SENTENCE repeated to the decoded length."
    )
    print()
    print(f"export const SENTENCE = {js_string(SENTENCE)};")
    print()
    print("export const FIXTURES = [")
    for name in names:
        headers = captures[name]["headers"]
        body = base64.b64decode(captures[name]["body"])
        decoded_length = int(headers["x-amz-decoded-content-length"])
        parts = split(body)
        assert rebuild(parts, decoded_length) == body, name
        print("  {")
        print(f"    name: '{name}',")
        print(f"    client: '{client(headers['user-agent'])}',")
        print(f"    contentSha256: '{headers['x-amz-content-sha256']}',")
        print(f"    decodedLength: {decoded_length},")
        if "x-amz-trailer" in headers:
            print(f"    trailer: '{headers['x-amz-trailer']}',")
        print("    body: [")
        for part in parts:
            print(f"      {part if isinstance(part, int) else js_string(part)},")
        print("    ],")
        print("  },")
    print("];")


if __name__ == "__main__":
    main()
