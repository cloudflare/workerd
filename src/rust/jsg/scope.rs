//! Locks for the handle scopes that C++ and V8 open before calling into Rust, and
//! [`Isolate`] for code that only needs the isolate lock.
//!
//! Every V8 handle lives in a `v8::HandleScope` and dies when that scope closes. A
//! [`Lock<'s>`](Lock) stands for the innermost open scope. It is only ever handed out as
//! `&'s mut Lock<'s>`, borrowed from the pinned storage of a [`CallbackScope`], and every API
//! that creates a handle returns a [`v8::Local<'s, _>`](crate::v8::Local), so the borrow
//! checker rejects any use of a handle after the callback returned.
//!
//! V8 callbacks generated by `jsg-macros` and builtin modules registered with
//! [`modules::add_builtin`](crate::modules::add_builtin) receive a lock without any `unsafe`.
//! Other Rust code that C++ calls with a scope open gets one from the `unsafe`
//! [`callback_scope!`], as in `rusty_v8`:
//!
//! ```ignore
//! // SAFETY: C++ calls this with the isolate locked, a context entered and a scope open.
//! jsg::callback_scope!(unsafe let lock, isolate);
//! let obj = lock.new_object();
//! ```
//!
//! ### Isolates
//!
//! Lifetimes tie a handle to its scope, not to that scope's isolate. To keep handles of one
//! isolate out of another, all scopes open on a thread at the same time must belong to one
//! isolate: opening a scope of another isolate while one is open panics. A handle cannot
//! outlive its scope, so every live handle belongs to the isolate of any lock it can be
//! used with. Code that needs scopes of two isolates open at once can open the second
//! isolate's scopes inside the `unsafe` [`allow_scopes_of_another_isolate`].
//!
//! Handles that outlive scopes remember their isolate and panic when used in another:
//! [`v8::Global`](crate::v8::Global) and the JavaScript wrapper of an [`Rc`](crate::Rc).
//!
use std::marker::PhantomData;
use std::marker::PhantomPinned;
use std::pin::Pin;
use std::sync::Arc;

use crate::isolate_state::IsolateState;
use crate::v8;

/// Proof that the V8 isolate is locked by the current thread, that a context is entered,
/// and that the `HandleScope` identified by `'s` is the innermost open one.
///
/// Mirrors `jsg::Lock&` in C++ JSG. User code never constructs a `Lock`: [`CallbackScope`]
/// hands out `&'s mut Lock<'s>`, where `'s` is the borrow of its pinned storage. Every handle
/// created through a lock is a [`v8::Local<'s, _>`](v8::Local) and cannot outlive that borrow.
///
/// `'s` is invariant, and `Lock` is neither `Send` nor `Sync`.
pub struct Lock<'s> {
    isolate: v8::IsolatePtr,
    _brand: PhantomData<*mut &'s ()>,
}

impl Lock<'_> {
    fn new(isolate: v8::IsolatePtr) -> Self {
        Self {
            isolate,
            _brand: PhantomData,
        }
    }

    /// Returns the raw pointer of the isolate associated with this lock. The pointer proves
    /// nothing about the lock; code that needs a locked isolate borrows the lock's [`Isolate`]
    /// through `Deref` instead.
    pub fn isolate(&self) -> v8::IsolatePtr {
        self.isolate
    }

    /// Returns the state shared by the handles of this lock's isolate.
    pub(crate) fn isolate_state(&mut self) -> &Arc<IsolateState> {
        self.realm().state()
    }
}

/// A V8 isolate that the current thread has locked.
///
/// It is only ever used by reference: `&'a mut Isolate` proves that the isolate is locked for
/// `'a`. Like any `&mut`, it is exclusive: while it is used, no other `Lock` or `Isolate`
/// reference for the isolate is, so methods taking `&mut self` may rely on that. Unlike a
/// [`Lock`], it requires no entered context and no open `HandleScope`, so it suits APIs that
/// only need the isolate lock. A `Lock` dereferences to its isolate; C++ that only locks the
/// isolate passes it to [`Isolate::from_raw`].
///
/// `Isolate` is neither `Send` nor `Sync`.
#[repr(C)]
pub struct Isolate {
    _opaque: [u8; 0],
    _not_send: PhantomData<*mut ()>,
}

impl Isolate {
    /// Borrows the isolate behind `isolate`.
    ///
    /// # Safety
    /// `isolate` must point to a valid `v8::Isolate` that this thread keeps locked for `'a`.
    /// No `Lock` or other `Isolate` reference for it may be used during `'a`.
    #[expect(unsafe_code, reason = "turns a raw isolate pointer into a reference")]
    pub unsafe fn from_raw<'a>(isolate: *mut v8::ffi::Isolate) -> &'a mut Self {
        // SAFETY: `isolate` points to a valid `v8::Isolate` (guaranteed by caller).
        debug_assert!(unsafe { v8::ffi::isolate_is_locked(isolate) });
        // SAFETY: the isolate is locked for `'a` and not otherwise referenced during `'a`
        // (guaranteed by caller). `Isolate` is zero-sized, so the reference covers no memory.
        unsafe { &mut *isolate.cast::<Self>() }
    }

    /// Returns the raw pointer to the `v8::Isolate`.
    pub fn as_ffi(&self) -> *mut v8::ffi::Isolate {
        std::ptr::from_ref(self).cast_mut().cast()
    }
}

impl std::ops::Deref for Lock<'_> {
    type Target = Isolate;

    #[expect(unsafe_code, reason = "borrows the lock's isolate")]
    fn deref(&self) -> &Isolate {
        // SAFETY: the lock proves the isolate is locked while it is borrowed, and `Isolate` is
        // zero-sized, so the reference covers no memory.
        unsafe { &*self.isolate.as_ffi().cast::<Isolate>() }
    }
}

impl std::ops::DerefMut for Lock<'_> {
    #[expect(unsafe_code, reason = "borrows the lock's isolate")]
    fn deref_mut(&mut self) -> &mut Isolate {
        // SAFETY: as in `deref`; the isolate is borrowed through the exclusive borrow of the
        // lock.
        unsafe { &mut *self.isolate.as_ffi().cast::<Isolate>() }
    }
}

/// Tracks which isolate owns the scopes open on this thread.
pub mod scope_owner {
    use std::cell::Cell;
    use std::ptr;

    use crate::v8;

    #[derive(Clone, Copy)]
    struct State {
        isolate: *mut v8::ffi::Isolate,
        depth: usize,
    }

    const NONE: State = State {
        isolate: ptr::null_mut(),
        depth: 0,
    };

    thread_local! {
        static STATE: Cell<State> = const { Cell::new(NONE) };
    }

    /// Records that a scope of `isolate` was opened.
    ///
    /// # Panics
    /// Panics if a scope of another isolate is open on this thread.
    pub fn enter(isolate: v8::IsolatePtr) {
        STATE.with(|state| {
            let mut s = state.get();
            if s.depth == 0 {
                s = State {
                    isolate: isolate.as_ffi(),
                    ..NONE
                };
            } else {
                assert!(
                    s.isolate == isolate.as_ffi(),
                    "attempt to open a scope of an isolate while a scope of another isolate is \
                     open on this thread"
                );
            }
            s.depth += 1;
            state.set(s);
        });
    }

    /// Records that a scope opened with [`enter`] was closed.
    pub fn exit() {
        STATE.with(|state| {
            let mut s = state.get();
            debug_assert!(s.depth > 0, "scope_owner::exit() without enter()");
            s.depth -= 1;
            state.set(s);
        });
    }

    /// Runs `f` as if no scope were open on this thread, and restores the open scopes after.
    pub fn suspend<R>(f: impl FnOnce() -> R) -> R {
        struct Restore(State);
        impl Drop for Restore {
            fn drop(&mut self) {
                STATE.with(|state| {
                    debug_assert_eq!(
                        state.get().depth,
                        0,
                        "a scope opened inside allow_scopes_of_another_isolate() is still open"
                    );
                    state.set(self.0);
                });
            }
        }
        let _restore = Restore(STATE.with(|state| state.replace(NONE)));
        f()
    }
}

/// Runs `f` with the scopes open on this thread set aside, so `f` can open scopes of
/// another isolate. They count as open again once `f` returns.
///
/// # Safety
///
/// While `f` runs, handles of the isolate whose scopes were set aside must not be used with
/// any other isolate, and handles that `f` creates must not be used once it returns. `f`
/// must close every scope it opens, and must not close any scope that was open when it was
/// called.
#[expect(
    unsafe_code,
    reason = "lifts the one-isolate-per-thread rule that keeps handles in their isolate"
)]
pub unsafe fn allow_scopes_of_another_isolate<R>(f: impl FnOnce() -> R) -> R {
    scope_owner::suspend(f)
}

/// What a [`CallbackScope`] can be created from.
pub trait CallbackScopeParam: callback_scope_param::Sealed {
    /// # Safety
    /// See [`CallbackScope::new`].
    #[doc(hidden)]
    #[expect(unsafe_code, reason = "reads the isolate from a raw pointer")]
    unsafe fn into_isolate(self) -> v8::IsolatePtr;
}

mod callback_scope_param {
    pub trait Sealed {}
    impl Sealed for *mut crate::v8::ffi::Isolate {}
    impl Sealed for *mut crate::v8::ffi::FunctionCallbackInfo {}
    impl Sealed for *mut crate::v8::ffi::PropertyCallbackInfo {}
    impl Sealed for *mut crate::v8::ffi::PropertySetterCallbackInfo {}
}

#[expect(unsafe_code, reason = "reads the isolate from a raw pointer")]
impl CallbackScopeParam for *mut v8::ffi::Isolate {
    /// # Panics
    /// Panics if the isolate is not locked by this thread or no context is entered: a C++
    /// caller bug that must not reach V8.
    unsafe fn into_isolate(self) -> v8::IsolatePtr {
        // SAFETY: the isolate is valid (guaranteed by caller).
        let locked = unsafe { v8::ffi::isolate_is_locked(self) };
        assert!(
            locked,
            "callback_scope!: the isolate is not locked by this thread"
        );
        // SAFETY: the isolate is valid and locked.
        let in_context = unsafe { v8::ffi::isolate_in_context(self) };
        assert!(in_context, "callback_scope!: no context is entered");
        // SAFETY: valid and locked, checked above.
        unsafe { v8::IsolatePtr::from_ffi(self) }
    }
}

#[expect(unsafe_code, reason = "reads the isolate from a raw pointer")]
impl CallbackScopeParam for *mut v8::ffi::FunctionCallbackInfo {
    unsafe fn into_isolate(self) -> v8::IsolatePtr {
        // SAFETY: V8 passes a valid FunctionCallbackInfo with the isolate locked (guaranteed
        // by caller).
        unsafe { v8::IsolatePtr::from_ffi(v8::ffi::fci_get_isolate(self)) }
    }
}

#[expect(unsafe_code, reason = "reads the isolate from a raw pointer")]
impl CallbackScopeParam for *mut v8::ffi::PropertyCallbackInfo {
    unsafe fn into_isolate(self) -> v8::IsolatePtr {
        // SAFETY: V8 passes a valid PropertyCallbackInfo with the isolate locked (guaranteed
        // by caller).
        unsafe { v8::IsolatePtr::from_ffi(v8::ffi::pci_get_isolate(self)) }
    }
}

#[expect(unsafe_code, reason = "reads the isolate from a raw pointer")]
impl CallbackScopeParam for *mut v8::ffi::PropertySetterCallbackInfo {
    unsafe fn into_isolate(self) -> v8::IsolatePtr {
        // SAFETY: V8 passes a valid PropertyCallbackInfo with the isolate locked (guaranteed
        // by caller).
        unsafe { v8::IsolatePtr::from_ffi(v8::ffi::psci_get_isolate(self)) }
    }
}

/// Storage of a lock for a `HandleScope` that C++ or V8 opened before calling into Rust.
/// Use [`callback_scope!`] to open one.
///
/// While it is open, it counts as a scope of its isolate for the one-isolate-per-thread rule.
pub struct CallbackScope {
    lock: Lock<'static>,
    open: bool,
    _pinned: PhantomPinned,
}

#[expect(unsafe_code, reason = "hands out a lock for a scope opened by C++")]
impl CallbackScope {
    /// Creates the storage of a lock for the innermost `HandleScope` of an isolate.
    ///
    /// # Safety
    /// `param` is either the `FunctionCallbackInfo`, `PropertyCallbackInfo` or
    /// `PropertySetterCallbackInfo` V8 passed to the running callback, or a valid isolate
    /// pointer. The isolate must be locked by this thread with a context entered, and its
    /// innermost `v8::HandleScope` must stay open and innermost until the storage is dropped.
    /// No other `Lock` for that `HandleScope` may be used while the storage lives. The
    /// storage must be dropped, not leaked, or its isolate keeps owning the thread.
    pub unsafe fn new(param: impl CallbackScopeParam) -> Self {
        Self {
            // SAFETY: forwarded from the caller.
            lock: Lock::new(unsafe { param.into_isolate() }),
            open: false,
            _pinned: PhantomPinned,
        }
    }

    /// Opens the scope and returns its lock.
    ///
    /// # Panics
    /// Panics if a scope of another isolate is open on this thread.
    pub fn open<'s>(self: Pin<&'s mut Self>) -> &'s mut Lock<'s> {
        // SAFETY: nothing is moved out of the storage.
        let this = unsafe { self.get_unchecked_mut() };
        if !this.open {
            scope_owner::enter(this.lock.isolate);
            this.open = true;
        }
        // SAFETY: `Lock<'s>` differs from `Lock<'static>` only in its brand; `new`'s caller
        // keeps the scope open and innermost while the storage lives.
        unsafe { &mut *(&raw mut this.lock).cast::<Lock<'s>>() }
    }

    pub(crate) const fn isolate(&self) -> v8::IsolatePtr {
        self.lock.isolate
    }
}

impl Drop for CallbackScope {
    fn drop(&mut self) {
        if self.open {
            scope_owner::exit();
        }
    }
}

/// A type with exactly one value, such as a function item or a closure that captures nothing.
///
/// Rust code that was handed such a value can recreate it from its type, which lets a callback
/// be called through a plain function pointer, without a data pointer next to it, as in
/// `rusty_v8`. See [`function_callback`].
pub trait UnitType: Copy {}

impl<T: Copy> UnitType for T {}

/// Recreates the value of the zero-sized type `T`.
///
/// # Safety
/// A value of `T` must have existed, for example one passed to the caller: a zero-sized type
/// can also have no values at all, like [`std::convert::Infallible`].
#[expect(unsafe_code, reason = "creates a zero-sized value")]
pub unsafe fn unit_value<T: UnitType>() -> T {
    const { assert!(size_of::<T>() == 0, "a callback must not capture anything") };
    // SAFETY: `T` is zero-sized, so it has at most one value and no bytes to initialize, and a
    // value of it existed (guaranteed by caller). `T: Copy`, so making another is no different
    // from copying it.
    unsafe { std::mem::MaybeUninit::<T>::zeroed().assume_init() }
}

/// A V8 function callback, as stored in function templates.
pub type RawFunctionCallback = unsafe extern "C" fn(*mut v8::ffi::FunctionCallbackInfo);

/// Turns `f` into a V8 function callback.
///
/// The callback opens a [`CallbackScope`] and calls `f` with its lock and the callback's
/// arguments. A panic in `f`, or a scope of another isolate
/// being open on the thread, throws an internal error to JavaScript and terminates execution.
///
/// `f` must capture nothing, which a compile-time assertion checks.
pub fn function_callback<F>(f: F) -> RawFunctionCallback
where
    F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::FunctionCallbackInfo<'s>),
{
    #[expect(unsafe_code, reason = "V8 calls this with a raw FunctionCallbackInfo")]
    unsafe extern "C" fn callback<F>(info: *mut v8::ffi::FunctionCallbackInfo)
    where
        F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::FunctionCallbackInfo<'s>),
    {
        // SAFETY: V8 calls a function callback with its `FunctionCallbackInfo`, with the isolate
        // locked, a context entered and a `HandleScope` open for the duration of the call.
        let scope = std::pin::pin!(unsafe { CallbackScope::new(info) });
        crate::catch_panic(scope, |lock| {
            // SAFETY: `info` is the running callback's, and `lock` the lock of its scope.
            let mut args = unsafe { v8::FunctionCallbackInfo::new(lock, info) };
            // SAFETY: `function_callback` was handed a value of `F`.
            let f = unsafe { unit_value::<F>() };
            f(lock, &mut args);
        });
    }

    let _ = f;
    callback::<F>
}

/// A V8 native data property getter (`AccessorNameGetterCallback`). The `usize` is the
/// `v8::Local` of the property name.
pub type RawGetterCallback = unsafe extern "C" fn(usize, *mut v8::ffi::PropertyCallbackInfo);

/// A V8 native data property setter (`AccessorNameSetterCallbackV2`). The `usize`s are the
/// `v8::Local`s of the property name and of the value assigned.
pub type RawSetterCallback =
    unsafe extern "C" fn(usize, usize, *mut v8::ffi::PropertySetterCallbackInfo);

/// Turns `f` into a V8 native data property getter, as [`function_callback`] does for
/// functions.
pub fn getter_callback<F>(f: F) -> RawGetterCallback
where
    F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::PropertyCallbackInfo<'s>),
{
    #[expect(unsafe_code, reason = "V8 calls this with a raw PropertyCallbackInfo")]
    unsafe extern "C" fn callback<F>(_name: usize, info: *mut v8::ffi::PropertyCallbackInfo)
    where
        F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::PropertyCallbackInfo<'s>),
    {
        // SAFETY: V8 calls a property getter with its `PropertyCallbackInfo`, with the isolate
        // locked, a context entered and a `HandleScope` open for the duration of the call.
        let scope = std::pin::pin!(unsafe { CallbackScope::new(info) });
        crate::catch_panic(scope, |lock| {
            // SAFETY: `info` is the running callback's, and `lock` the lock of its scope.
            let mut args = unsafe { v8::PropertyCallbackInfo::new(lock, info) };
            // SAFETY: `getter_callback` was handed a value of `F`.
            let f = unsafe { unit_value::<F>() };
            f(lock, &mut args);
        });
    }

    let _ = f;
    callback::<F>
}

/// Turns `f` into a V8 native data property setter, as [`function_callback`] does for
/// functions.
pub fn setter_callback<F>(f: F) -> RawSetterCallback
where
    F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::PropertySetterCallbackInfo<'s>),
{
    #[expect(
        unsafe_code,
        reason = "V8 calls this with a raw PropertySetterCallbackInfo"
    )]
    unsafe extern "C" fn callback<F>(
        _name: usize,
        value: usize,
        info: *mut v8::ffi::PropertySetterCallbackInfo,
    ) where
        F: UnitType + for<'s> Fn(&mut Lock<'s>, &mut v8::PropertySetterCallbackInfo<'s>),
    {
        // SAFETY: V8 calls a property setter with its `PropertyCallbackInfo` and the value
        // assigned, with the isolate locked, a context entered and a `HandleScope` open for
        // the duration of the call.
        let scope = std::pin::pin!(unsafe { CallbackScope::new(info) });
        crate::catch_panic(scope, |lock| {
            // SAFETY: `info` and `value` are the running callback's, and `lock` the lock of its
            // scope.
            let mut args = unsafe { v8::PropertySetterCallbackInfo::new(lock, info, value) };
            // SAFETY: `setter_callback` was handed a value of `F`.
            let f = unsafe { unit_value::<F>() };
            f(lock, &mut args);
        });
    }

    let _ = f;
    callback::<F>
}

/// Binds to `$lock` a lock for the `HandleScope` that C++ or V8 opened before calling into
/// Rust; see [`CallbackScope::new`] for what the caller must guarantee.
///
/// `$param` is the `*mut FunctionCallbackInfo`, `*mut PropertyCallbackInfo` or
/// `*mut PropertySetterCallbackInfo` of a V8 callback, or a `*mut Isolate`.
///
/// ```ignore
/// jsg::callback_scope!(unsafe let lock, isolate);
/// ```
#[macro_export]
macro_rules! callback_scope {
    (unsafe let $lock:ident, $param:expr $(,)?) => {
        // Evaluated outside the `unsafe` block, so `$param` gets no unsafe context.
        let param = $param;
        // SAFETY: the `unsafe` in the invocation passes the obligation to its caller.
        let mut $lock = ::std::pin::pin!(unsafe { $crate::CallbackScope::new(param) });
        let $lock = $lock.as_mut().open();
    };
}
