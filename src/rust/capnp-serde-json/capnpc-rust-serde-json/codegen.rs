/// `capnp/compat/json.capnp`'s `Value`, which the C++ codec copies as raw JSON.
const JSON_VALUE_ID: u64 = 0xa3fa_7845_f919_dd83;
/// `$Json.name`.
const JSON_NAME_ID: u64 = 0xfa5b_1fd6_1c2e_7c3d;
/// `$Json.flatten`.
const JSON_FLATTEN_ID: u64 = 0x82d3_e852_af03_36bf;
/// `$Json.discriminator`.
const JSON_DISCRIMINATOR_ID: u64 = 0xcfa7_94e8_d19a_0162;
/// `$Json.base64`.
const JSON_BASE64_ID: u64 = 0xd7d8_7945_0a25_3e4b;
/// `$Json.hex`.
const JSON_HEX_ID: u64 = 0xf061_e22f_0ae5_c7b5;

const DERIVES: &str = "#[derive(::core::clone::Clone, ::core::fmt::Debug, ::core::cmp::PartialEq, \
                       ::serde::Serialize, ::serde::Deserialize)]";
const DEFAULT: &str = "::core::default::Default::default()";

/// Generates a Rust source file for each file the request asks for, and if `ffi`, its cxx bridge
/// (see `ffi.rs`). Returns the files' paths, relative to the output directory, and contents.
pub fn generate(
    request: code_generator_request::Reader,
    ffi: bool,
) -> Result<Vec<(String, String)>> {
    let generator = Generator::new(request)?;
    let mut items = HashSet::new();
    let mut files = Vec::new();
    for requested in request.get_requested_files()? {
        let filename = requested.get_filename()?.to_str()?;
        let mut out = Output {
            code: String::new(),
            items: &mut items,
        };
        out.line(
            0,
            &format!("// Generated by capnpc-rust-serde-json from {filename}. DO NOT EDIT."),
        );
        generator
            .gen_nested(&mut out, requested.get_id())
            .with_context(|| format!("generating {filename}"))?;
        files.push((output_path(filename), out.code));
    }
    if ffi {
        for requested in request.get_requested_files()? {
            let filename = requested.get_filename()?.to_str()?;
            let code = ffi::generate(&generator, requested.get_id(), filename, &mut items)
                .with_context(|| format!("generating the cxx bridge of {filename}"))?;
            files.push((ffi::output_path(filename), code));
        }
    }
    Ok(files)
}

/// The path of the Rust file generated from the schema file at `filename`: `foo/bar-baz.capnp`
/// becomes `foo/bar_baz_serde_json.rs`.
pub fn output_path(filename: &str) -> String {
    let (dir, base) = filename
        .rfind('/')
        .map_or(("", filename), |slash| filename.split_at(slash + 1));
    let stem = base.strip_suffix(".capnp").unwrap_or(base);
    format!("{dir}{}_serde_json.rs", stem.replace('-', "_"))
}

/// Generated code, and the names of the items generated so far, which must be unique since every
/// file is included at the crate root.
struct Output<'a> {
    code: String,
    items: &'a mut HashSet<String>,
}

impl Output<'_> {
    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.code.push_str("    ");
        }
        self.code.push_str(text);
        self.code.push('\n');
    }

    fn blank(&mut self) {
        self.code.push('\n');
    }

    fn doc(&mut self, indent: usize, doc: Option<&str>) {
        for line in doc.unwrap_or_default().lines() {
            let line = line.trim_end();
            if line.is_empty() {
                self.line(indent, "///");
            } else {
                self.line(indent, &format!("/// {line}"));
            }
        }
    }

    fn serde(&mut self, indent: usize, attributes: &[String]) {
        if !attributes.is_empty() {
            self.line(indent, &format!("#[serde({})]", attributes.join(", ")));
        }
    }

    fn item(&mut self, name: &str) -> Result<()> {
        if !self.items.insert(name.to_owned()) {
            bail!("more than one item would be named `{name}`");
        }
        Ok(())
    }
}

/// A union's `$Json.discriminator`.
#[derive(Clone, Default)]
struct Discriminator {
    name: Option<String>,
    value_name: Option<String>,
}

/// The `$Json` annotations of a field or a node.
#[derive(Default)]
struct JsonAnnotations {
    name: Option<String>,
    /// The `$Json.flatten` prefix, if flattened.
    flatten: Option<String>,
    discriminator: Option<Discriminator>,
    base64: bool,
    hex: bool,
}

impl JsonAnnotations {
    fn read(annotations: struct_list::Reader<annotation::Owned>) -> Result<Self> {
        let mut result = Self::default();
        for annotation in annotations {
            let value = annotation.get_value()?;
            match annotation.get_id() {
                JSON_NAME_ID => {
                    if let value::Text(text) = value.which()? {
                        result.name = Some(text?.to_string()?);
                    }
                }
                JSON_FLATTEN_ID => {
                    let options = struct_value(value)?;
                    result.flatten = Some(options.text(0)?.unwrap_or_default());
                }
                JSON_DISCRIMINATOR_ID => {
                    let options = struct_value(value)?;
                    result.discriminator = Some(Discriminator {
                        name: options.text(0)?,
                        value_name: options.text(1)?,
                    });
                }
                JSON_BASE64_ID => result.base64 = true,
                JSON_HEX_ID => result.hex = true,
                _ => {}
            }
        }
        Ok(result)
    }
}

/// The struct value of an annotation whose struct type has only `Text` fields, which is all this
/// generator reads: `FlattenOptions` and `DiscriminatorOptions`. This crate has no generated code
/// for `json.capnp`, so it reads them by pointer index.
struct TextFields<'a>(StructReader<'a>);

impl<'a> FromPointerReader<'a> for TextFields<'a> {
    fn get_from_pointer(
        reader: &PointerReader<'a>,
        default: Option<&'a [capnp::Word]>,
    ) -> capnp::Result<Self> {
        Ok(Self(reader.get_struct(default)?))
    }
}

impl TextFields<'_> {
    fn text(&self, index: usize) -> Result<Option<String>> {
        let pointer = self.0.get_pointer_field(index);
        if pointer.is_null() {
            return Ok(None);
        }
        Ok(Some(pointer.get_text(None)?.to_string()?))
    }
}

fn struct_value(value: value::Reader) -> Result<TextFields> {
    match value.which()? {
        value::Struct(pointer) => Ok(pointer.get_as()?),
        _ => bail!("expected a struct annotation value"),
    }
}

/// A field of a struct or a group.
struct Field<'a> {
    reader: field::Reader<'a>,
    name: String,
    json: JsonAnnotations,
    /// The field's name in JSON.
    json_name: String,
    doc: Option<String>,
}

impl Field<'_> {
    fn is_union_member(&self) -> bool {
        self.reader.get_discriminant_value() != field::NO_DISCRIMINANT
    }

    /// Whether the field has `$Json.flatten()`. A prefix is an error.
    fn flattened(&self) -> Result<bool> {
        match self.json.flatten.as_deref() {
            None => Ok(false),
            Some("") => Ok(true),
            Some(prefix) => bail!(
                "field `{}`: $Json.flatten(prefix = {prefix:?}) is not supported",
                self.name
            ),
        }
    }

    /// Fails if the field is a slot with a schema default, which only `Bool` and integer fields
    /// that are not union members may have.
    fn check_no_default(&self) -> Result<()> {
        if let field::Slot(slot) = self.reader.which()?
            && slot.get_had_explicit_default()
        {
            bail!("field `{}`: its schema default is not supported", self.name);
        }
        Ok(())
    }
}

/// What a named union's group field says about the union.
struct GroupContext {
    discriminator: Option<Discriminator>,
    doc: Option<String>,
}

impl GroupContext {
    fn new(field: &Field) -> Self {
        Self {
            discriminator: field.json.discriminator.clone(),
            doc: field.doc.clone(),
        }
    }
}

/// How a union is tagged in JSON: by the discriminator field `tag`, if internally tagged.
struct Tagging {
    tag: Option<String>,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Kind {
    /// `Void`, as a union member.
    Void,
    /// `Bool` or an integer: a value with a schema default.
    Primitive,
    /// `Text`, `Data`, a list or a struct: a value that may be null.
    Pointer,
}

/// The Rust type of a Cap'n Proto type.
struct RustType {
    ty: String,
    /// The `capnp_serde_json` marker type that serializes it, if serde's own serialization differs
    /// from the C++ codec's.
    marker: Option<String>,
    kind: Kind,
    /// The struct, if the type is a struct generated by this plugin.
    struct_id: Option<u64>,
}

impl RustType {
    fn new(ty: &str, marker: Option<&str>, kind: Kind) -> Self {
        Self {
            ty: ty.to_owned(),
            marker: marker.map(|marker| format!("::capnp_serde_json::{marker}")),
            kind,
            struct_id: None,
        }
    }

    fn with_attribute(&self) -> Option<String> {
        self.marker
            .as_ref()
            .map(|marker| format!("with = \"::capnp_serde_json::As::<{marker}>\""))
    }
}

struct Generator<'a> {
    nodes: HashMap<u64, node::Reader<'a>>,
    docs: HashMap<u64, node::source_info::Reader<'a>>,
    /// Rust names of structs, groups and enums.
    names: HashMap<u64, String>,
    /// Rust names of constants.
    const_names: HashMap<u64, String>,
}

impl<'a> Generator<'a> {
    fn new(request: code_generator_request::Reader<'a>) -> Result<Self> {
        let mut generator = Self {
            nodes: HashMap::new(),
            docs: HashMap::new(),
            names: HashMap::new(),
            const_names: HashMap::new(),
        };
        for node in request.get_nodes()? {
            generator.nodes.insert(node.get_id(), node);
        }
        for info in request.get_source_info()? {
            generator.docs.insert(info.get_id(), info);
        }
        let files: Vec<node::Reader> = generator
            .nodes
            .values()
            .filter(|node| matches!(node.which(), Ok(node::File(()))))
            .copied()
            .collect();
        for file in files {
            generator.assign_names(file, "")?;
        }
        Ok(generator)
    }

    /// Names the nodes nested in `scope`, prefixing the names with `prefix`, the scope's name.
    fn assign_names(&mut self, scope: node::Reader<'a>, prefix: &str) -> Result<()> {
        for nested in scope.get_nested_nodes()? {
            let id = nested.get_id();
            let Some(&child) = self.nodes.get(&id) else {
                continue;
            };
            let name = nested.get_name()?.to_str()?;
            let full_name = format!("{prefix}{}", pascal_case(name));
            match child.which()? {
                node::Struct(st) => {
                    self.names.insert(id, full_name.clone());
                    self.assign_group_names(st, &full_name)?;
                    self.assign_names(child, &full_name)?;
                }
                node::Enum(_) => {
                    self.names.insert(id, full_name);
                }
                node::Const(_) => {
                    let name = if prefix.is_empty() {
                        screaming_snake_case(name)
                    } else {
                        format!(
                            "{}_{}",
                            screaming_snake_case(prefix),
                            screaming_snake_case(name)
                        )
                    };
                    self.const_names.insert(id, name);
                }
                node::Interface(_) => self.assign_names(child, &full_name)?,
                node::File(()) | node::Annotation(_) => {}
            }
        }
        Ok(())
    }

    fn assign_group_names(&mut self, st: node::struct_::Reader<'a>, prefix: &str) -> Result<()> {
        for field in st.get_fields()? {
            if let field::Group(group) = field.which()? {
                let id = group.get_type_id();
                let name = format!("{prefix}{}", pascal_case(field.get_name()?.to_str()?));
                self.names.insert(id, name.clone());
                if let node::Struct(group_struct) = self.node(id)?.which()? {
                    self.assign_group_names(group_struct, &name)?;
                }
            }
        }
        Ok(())
    }

    fn node(&self, id: u64) -> Result<node::Reader<'a>> {
        self.nodes
            .get(&id)
            .copied()
            .ok_or_else(|| anyhow!("no schema for node {id:#x}"))
    }

    fn struct_node(&self, id: u64) -> Result<node::struct_::Reader<'a>> {
        match self.node(id)?.which()? {
            node::Struct(st) => Ok(st),
            _ => bail!("node {id:#x} is not a struct"),
        }
    }

    fn name(&self, id: u64) -> Result<&str> {
        self.names
            .get(&id)
            .map(String::as_str)
            .ok_or_else(|| anyhow!("no name for node {id:#x}"))
    }

    fn display_name(&self, id: u64) -> String {
        self.node(id)
            .ok()
            .and_then(|node| node.get_display_name().ok())
            .and_then(|name| name.to_string().ok())
            .unwrap_or_else(|| format!("{id:#x}"))
    }

    fn doc(&self, id: u64) -> Option<String> {
        let doc = self
            .docs
            .get(&id)?
            .get_doc_comment()
            .ok()?
            .to_string()
            .ok()?;
        (!doc.is_empty()).then_some(doc)
    }

    fn member_doc(&self, id: u64, index: u32) -> Option<String> {
        let members = self.docs.get(&id)?.get_members().ok()?;
        if index >= members.len() {
            return None;
        }
        let doc = members
            .get(index)
            .get_doc_comment()
            .ok()?
            .to_string()
            .ok()?;
        (!doc.is_empty()).then_some(doc)
    }

    fn fields(&self, id: u64) -> Result<Vec<Field<'a>>> {
        let mut fields = Vec::new();
        for (index, reader) in (0..).zip(self.struct_node(id)?.get_fields()?) {
            let name = reader.get_name()?.to_string()?;
            let json = JsonAnnotations::read(reader.get_annotations()?)?;
            let json_name = json.name.clone().unwrap_or_else(|| name.clone());
            fields.push(Field {
                reader,
                name,
                json,
                json_name,
                doc: self.member_doc(id, index),
            });
        }
        Ok(fields)
    }

    /// Generates the items for the nodes nested in `scope`.
    fn gen_nested(&self, out: &mut Output, scope: u64) -> Result<()> {
        for nested in self.node(scope)?.get_nested_nodes()? {
            let id = nested.get_id();
            let Ok(child) = self.node(id) else {
                continue;
            };
            let result = match child.which()? {
                node::Struct(_) => self.gen_struct(out, id),
                node::Const(_) => self.gen_const(out, id),
                // Enums are not supported, but a schema may declare them, if no field uses them.
                node::Enum(_) | node::File(()) | node::Annotation(_) => Ok(()),
                node::Interface(_) => Err(anyhow!("interfaces are not supported")),
            };
            result.with_context(|| self.display_name(id))?;
        }
        Ok(())
    }

    fn gen_struct(&self, out: &mut Output, id: u64) -> Result<()> {
        let node = self.node(id)?;
        if node.get_is_generic() {
            bail!("generic structs are not supported");
        }
        if JsonAnnotations::read(node.get_annotations()?)?
            .discriminator
            .is_some()
        {
            bail!("$Json.discriminator on a struct is not supported; name its union");
        }
        let name = self.name(id)?.to_owned();
        out.item(&name)?;
        let fields = self.fields(id)?;
        let (union_fields, plain_fields): (Vec<&Field>, Vec<&Field>) =
            fields.iter().partition(|field| field.is_union_member());

        out.blank();
        out.doc(0, self.doc(id).as_deref());
        out.line(0, DERIVES);
        // Missing fields take the values of the `Default` impl below: their schema defaults.
        out.line(0, "#[serde(default)]");
        out.line(0, &format!("pub struct {name} {{"));
        let mut defaults = Vec::new();
        for field in &plain_fields {
            let (ident, default) = self
                .gen_struct_field(out, id, field)
                .with_context(|| format!("field `{}`", field.name))?;
            if defaults.iter().any(|(existing, _)| *existing == ident) {
                bail!("more than one field would be named `{ident}`");
            }
            defaults.push((ident, default));
        }
        let union_name = format!("{name}Which");
        if !union_fields.is_empty() {
            if defaults.iter().any(|(existing, _)| existing == "which") {
                bail!("a field named `which` clashes with the field that holds the union");
            }
            out.line(1, "#[serde(flatten)]");
            out.line(1, &format!("pub which: {union_name},"));
            defaults.push(("which".to_owned(), DEFAULT.to_owned()));
        }
        out.line(0, "}");

        out.blank();
        out.line(0, &format!("impl ::core::default::Default for {name} {{"));
        out.line(1, "fn default() -> Self {");
        out.line(2, "Self {");
        for (ident, default) in &defaults {
            out.line(3, &format!("{ident}: {default},"));
        }
        out.line(2, "}");
        out.line(1, "}");
        out.line(0, "}");

        if !union_fields.is_empty() {
            out.item(&union_name)?;
            let doc = format!("The unnamed union of [`{name}`].");
            let tagging = Tagging { tag: None };
            self.gen_union(out, id, &union_name, &union_fields, &tagging, Some(&doc))?;
        }
        self.gen_groups(out, &fields)?;
        self.gen_nested(out, id)
    }

    /// Generates a field of struct `scope`. Returns its identifier and its default value.
    fn gen_struct_field(
        &self,
        out: &mut Output,
        scope: u64,
        field: &Field,
    ) -> Result<(String, String)> {
        let ident = identifier(&snake_case(&field.name));
        let mut attributes = Vec::new();
        let flattened = field.flattened()?;
        let (ty, default) = match field.reader.which()? {
            field::Group(group) => {
                let id = group.get_type_id();
                if !self.is_named_union(id)? {
                    bail!("groups other than named unions are not supported");
                }
                if !flattened {
                    bail!("a named union needs $Json.flatten()");
                }
                // A flattened field's own name does not appear in JSON.
                attributes.push("flatten".to_owned());
                (self.name(id)?.to_owned(), DEFAULT.to_owned())
            }
            field::Slot(slot) => {
                if flattened {
                    bail!("$Json.flatten() is only supported on named unions and union members");
                }
                if unraw(&ident) != field.json_name {
                    attributes.push(format!("rename = {:?}", field.json_name));
                }
                let rust_type = self.field_type(scope, field, slot.get_type()?)?;
                match rust_type.kind {
                    Kind::Void => bail!("Void fields are not supported"),
                    Kind::Pointer => {
                        field.check_no_default()?;
                        attributes.push(
                            "skip_serializing_if = \"::std::option::Option::is_none\"".to_owned(),
                        );
                        if let Some(marker) = &rust_type.marker {
                            attributes.push(format!(
                                "with = \"::capnp_serde_json::As::<::std::option::Option<{marker}>>\""
                            ));
                        }
                        (
                            format!("::std::option::Option<{}>", rust_type.ty),
                            "::std::option::Option::None".to_owned(),
                        )
                    }
                    Kind::Primitive => {
                        let (default, predicate) =
                            Self::primitive_default(slot.get_default_value()?)?;
                        attributes.push(format!("skip_serializing_if = \"{predicate}\""));
                        attributes.extend(rust_type.with_attribute());
                        (rust_type.ty, default)
                    }
                }
            }
        };
        out.doc(1, field.doc.as_deref());
        out.serde(1, &attributes);
        out.line(1, &format!("pub {ident}: {ty},"));
        Ok((ident, default))
    }

    /// Whether group `id` is a named union, generated as its enum: all its fields are members of
    /// its union.
    fn is_named_union(&self, id: u64) -> Result<bool> {
        let st = self.struct_node(id)?;
        Ok(st.get_discriminant_count() > 0
            && u32::from(st.get_discriminant_count()) == st.get_fields()?.len())
    }

    /// Generates the enums of the named unions among `fields`, which `gen_struct_field` checked.
    fn gen_groups(&self, out: &mut Output, fields: &[Field]) -> Result<()> {
        for field in fields {
            let field::Group(group) = field.reader.which()? else {
                continue;
            };
            let id = group.get_type_id();
            let context = GroupContext::new(field);
            let name = self.name(id)?.to_owned();
            out.item(&name)?;
            let members = self.fields(id)?;
            let members: Vec<&Field> = members.iter().collect();
            let tagging =
                Self::union_tagging(&context).with_context(|| format!("union `{}`", field.name))?;
            self.gen_union(out, id, &name, &members, &tagging, context.doc.as_deref())?;
        }
        Ok(())
    }

    /// How the named union whose group field says `context` is tagged.
    fn union_tagging(context: &GroupContext) -> Result<Tagging> {
        let Some(discriminator) = &context.discriminator else {
            return Ok(Tagging { tag: None });
        };
        if discriminator.value_name.is_some() {
            bail!("$Json.discriminator(valueName) is not supported");
        }
        let Some(tag) = &discriminator.name else {
            bail!("$Json.discriminator needs a name");
        };
        Ok(Tagging {
            tag: Some(tag.clone()),
        })
    }

    /// Generates the enum `name` for a union whose members are `members`, fields of `scope`.
    fn gen_union(
        &self,
        out: &mut Output,
        scope: u64,
        name: &str,
        members: &[&Field],
        tagging: &Tagging,
        doc: Option<&str>,
    ) -> Result<()> {
        out.blank();
        out.doc(0, doc);
        out.line(0, DERIVES);
        if let Some(tag) = &tagging.tag {
            out.line(0, &format!("#[serde(tag = {tag:?})]"));
        }
        out.line(0, &format!("pub enum {name} {{"));
        let mut variants = HashSet::new();
        let mut default = None;
        for member in members {
            let (variant, construct) = self
                .gen_union_member(out, scope, member, tagging)
                .with_context(|| format!("union member `{}`", member.name))?;
            if !variants.insert(variant.clone()) {
                bail!("more than one variant would be named `{variant}`");
            }
            if member.reader.get_discriminant_value() == 0 {
                default = Some(construct);
            }
        }
        out.line(0, "}");

        let default = default.ok_or_else(|| anyhow!("union `{name}` has no first member"))?;
        out.blank();
        out.line(0, &format!("impl ::core::default::Default for {name} {{"));
        out.line(1, "fn default() -> Self {");
        out.line(2, &default);
        out.line(1, "}");
        out.line(0, "}");
        Ok(())
    }

    /// Generates the variant of union member `member`, a field of `scope`. Returns the variant's
    /// name and the expression that constructs it with the member's default value, the union's
    /// default if the member is its first.
    fn gen_union_member(
        &self,
        out: &mut Output,
        scope: u64,
        member: &Field,
        tagging: &Tagging,
    ) -> Result<(String, String)> {
        let variant = identifier(&pascal_case(&member.name));
        let flattened = member.flattened()?;
        let field::Slot(slot) = member.reader.which()? else {
            bail!("groups as union members are not supported");
        };
        member.check_no_default()?;
        let rust_type = self.field_type(scope, member, slot.get_type()?)?;

        out.doc(1, member.doc.as_deref());
        out.line(1, &format!("#[serde(rename = {:?})]", member.json_name));
        let construct = if tagging.tag.is_some() {
            match (rust_type.kind, flattened, rust_type.struct_id) {
                (Kind::Void, false, _) => {
                    out.line(1, &format!("{variant},"));
                    format!("Self::{variant}")
                }
                (Kind::Pointer, true, Some(_)) => {
                    out.line(1, &format!("{variant}({}),", rust_type.ty));
                    format!("Self::{variant}({DEFAULT})")
                }
                _ => {
                    bail!("members of an internally tagged union must be Void or flattened structs")
                }
            }
        } else {
            if flattened {
                bail!("a flattened union member needs $Json.discriminator on its union");
            }
            let default = match rust_type.kind {
                Kind::Void => bail!("Void members need $Json.discriminator on their union"),
                Kind::Primitive => Self::primitive_default(slot.get_default_value()?)?.0,
                Kind::Pointer => DEFAULT.to_owned(),
            };
            match rust_type.with_attribute() {
                Some(with) => {
                    out.line(1, &format!("{variant}(#[serde({with})] {}),", rust_type.ty));
                }
                None => out.line(1, &format!("{variant}({}),", rust_type.ty)),
            }
            format!("Self::{variant}({default})")
        };
        Ok((variant, construct))
    }

    fn gen_const(&self, out: &mut Output, id: u64) -> Result<()> {
        let node::Const(constant) = self.node(id)?.which()? else {
            bail!("not a constant");
        };
        let name = self
            .const_names
            .get(&id)
            .ok_or_else(|| anyhow!("no name for constant {id:#x}"))?
            .clone();
        let rust_type = self.rust_type(constant.get_type()?)?;
        if rust_type.kind != Kind::Primitive {
            bail!("only constants of Bool and integer types are supported");
        }
        let literal = Self::primitive_default(constant.get_value()?)?.0;
        out.item(&name)?;
        out.blank();
        out.doc(0, self.doc(id).as_deref());
        out.line(
            0,
            &format!("pub const {name}: {} = {literal};", rust_type.ty),
        );
        Ok(())
    }

    /// The Rust type of a field of `scope` whose type is `ty`, taking the field's annotations into
    /// account.
    fn field_type(&self, scope: u64, field: &Field, ty: type_::Reader) -> Result<RustType> {
        let mut rust_type = self.rust_type(ty)?;
        let is_data = matches!(ty.which()?, type_::Data(()));
        if (field.json.base64 || field.json.hex) && !is_data {
            bail!("only Data can be base64 or hex");
        }
        if is_data {
            let marker = match (field.json.base64, field.json.hex) {
                (true, false) => "Base64",
                (false, true) => "Hex",
                _ => bail!("Data needs one of $Json.base64 and $Json.hex"),
            };
            rust_type.marker = Some(format!("::capnp_serde_json::{marker}"));
        }
        if let Some(id) = rust_type.struct_id
            && self.contains(id, scope, &mut HashSet::new())?
        {
            bail!(
                "{} contains {}, which is not supported",
                self.display_name(id),
                self.display_name(scope)
            );
        }
        Ok(rust_type)
    }

    fn rust_type(&self, ty: type_::Reader) -> Result<RustType> {
        Ok(match ty.which()? {
            type_::Void(()) => RustType::new("()", None, Kind::Void),
            type_::Bool(()) => RustType::new("bool", None, Kind::Primitive),
            type_::Int8(()) => RustType::new("i8", None, Kind::Primitive),
            type_::Int16(()) => RustType::new("i16", None, Kind::Primitive),
            type_::Int32(()) => RustType::new("i32", None, Kind::Primitive),
            type_::Int64(()) => RustType::new("i64", Some("Int64"), Kind::Primitive),
            type_::Uint8(()) => RustType::new("u8", None, Kind::Primitive),
            type_::Uint16(()) => RustType::new("u16", None, Kind::Primitive),
            type_::Uint32(()) => RustType::new("u32", None, Kind::Primitive),
            type_::Uint64(()) => RustType::new("u64", Some("Int64"), Kind::Primitive),
            type_::Float32(()) | type_::Float64(()) => bail!("floats are not supported"),
            type_::Enum(_) => bail!("enums are not supported"),
            type_::Text(()) => RustType::new("::std::string::String", None, Kind::Pointer),
            // `field_type` adds the marker of the encoding.
            type_::Data(()) => RustType::new("::std::vec::Vec<u8>", None, Kind::Pointer),
            type_::List(list) => {
                let element_type = list.get_element_type()?;
                let element = match element_type.which()? {
                    type_::Int8(())
                    | type_::Int16(())
                    | type_::Int32(())
                    | type_::Int64(())
                    | type_::Uint8(())
                    | type_::Uint16(())
                    | type_::Uint32(())
                    | type_::Uint64(())
                    | type_::Text(())
                    | type_::Struct(_) => self.rust_type(element_type)?,
                    _ => bail!("only lists of integers, Text and structs are supported"),
                };
                RustType {
                    ty: format!("::std::vec::Vec<{}>", element.ty),
                    marker: element
                        .marker
                        .map(|marker| format!("::std::vec::Vec<{marker}>")),
                    kind: Kind::Pointer,
                    struct_id: None,
                }
            }
            type_::Struct(st) => {
                let id = st.get_type_id();
                if id == JSON_VALUE_ID {
                    bail!("Json.Value is not supported");
                }
                if self.node(id)?.get_is_generic() {
                    bail!("generic struct {} is not supported", self.display_name(id));
                }
                let mut rust_type = RustType::new(self.name(id)?, None, Kind::Pointer);
                rust_type.struct_id = Some(id);
                rust_type
            }
            type_::Interface(_) => bail!("interfaces are not supported"),
            type_::AnyPointer(_) => bail!("AnyPointer is not supported"),
        })
    }

    /// Whether a value of struct or group `id` holds `target` inline, not behind a list, so that
    /// its Rust type would have infinite size.
    fn contains(&self, id: u64, target: u64, visited: &mut HashSet<u64>) -> Result<bool> {
        if id == target {
            return Ok(true);
        }
        if !visited.insert(id) {
            return Ok(false);
        }
        for field in self.struct_node(id)?.get_fields()? {
            let inner = match field.which()? {
                field::Group(group) => Some(group.get_type_id()),
                field::Slot(slot) => match slot.get_type()?.which()? {
                    type_::Struct(st) => Some(st.get_type_id()),
                    _ => None,
                },
            };
            if let Some(inner) = inner
                && self.contains(inner, target, visited)?
            {
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// The Rust expression for a `Bool` or integer value, and the `skip_serializing_if`
    /// predicate that recognizes it.
    fn primitive_default(value: value::Reader) -> Result<(String, String)> {
        fn integer<T: std::fmt::Display + Default + PartialEq + Copy>(
            value: T,
            suffix: &str,
        ) -> (String, String) {
            let literal = value.to_string();
            let predicate = if value == T::default() {
                "::capnp_serde_json::is_default".to_owned()
            } else if literal.starts_with('-') {
                format!("::capnp_serde_json::eq_{suffix}::<{{ {literal} }}>")
            } else {
                format!("::capnp_serde_json::eq_{suffix}::<{literal}>")
            };
            (literal, predicate)
        }

        Ok(match value.which()? {
            value::Bool(value) => (
                value.to_string(),
                if value {
                    "::capnp_serde_json::eq_bool::<true>"
                } else {
                    "::capnp_serde_json::is_default"
                }
                .to_owned(),
            ),
            value::Int8(value) => integer(value, "i8"),
            value::Int16(value) => integer(value, "i16"),
            value::Int32(value) => integer(value, "i32"),
            value::Int64(value) => integer(value, "i64"),
            value::Uint8(value) => integer(value, "u8"),
            value::Uint16(value) => integer(value, "u16"),
            value::Uint32(value) => integer(value, "u32"),
            value::Uint64(value) => integer(value, "u64"),
            _ => bail!("not a Bool or integer value"),
        })
    }
}

