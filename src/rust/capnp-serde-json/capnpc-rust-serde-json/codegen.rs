//! Generates Rust types from the schemas of a `CodeGeneratorRequest`.
//!
//! Each struct becomes a Rust struct and each union a Rust enum, deriving `Serialize` and
//! `Deserialize` with serde attributes that reproduce the JSON of the C++ `capnp::JsonCodec` with
//! `handleByAnnotation()` and `HasMode::NON_DEFAULT`; see `capnp_serde_json` for the conventions.
//! The `$Json` annotations map onto serde as follows:
//!
//! - `$Json.name` renames a field or a union member.
//! - `$Json.flatten()` on a named union or a union member is `#[serde(flatten)]`.
//! - A named union with `$Json.discriminator(name = ...)` is an internally tagged enum,
//!   `#[serde(tag = ...)]`; one without it, and a struct's unnamed union, are externally tagged,
//!   the union member's name being its key. Both are flattened into the struct.
//! - `$Json.base64` and `$Json.hex` select the `capnp_serde_json::Base64` and
//!   `capnp_serde_json::Hex` encodings of `Data`.
//!
//! The generator supports what the schemas it is used for need, and fails with an error naming
//! the declaration for anything else, rather than reproduce every behaviour of the C++ codec. The
//! compatibility table of `src/rust/capnp-serde-json/README.md` lists what it supports and what
//! it rejects; keep it in step with the checks here.
//!
//! The README also lists how the types' JSON differs from the C++ codec's.

