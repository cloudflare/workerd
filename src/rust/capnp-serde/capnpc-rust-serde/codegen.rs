//! Generates Rust types from the schemas of a `CodeGeneratorRequest`.
//!
//! Each struct becomes a Rust struct, each enum a Rust enum, and each union a Rust enum, with serde
//! attributes that reproduce the JSON of the C++ `capnp::JsonCodec` with `handleByAnnotation()`
//! and `HasMode::NON_DEFAULT`; see `capnp_serde` for the conventions. The `$Json` annotations
//! map onto serde as follows:
//!
//! - `$Json.name` renames a field, a union member or an enumerant.
//! - `$Json.flatten` without a prefix is `#[serde(flatten)]`. A prefix has no serde equivalent and
//!   is rejected.
//! - A union with `$Json.discriminator` is an internally tagged enum, `#[serde(tag = ...)]`; one
//!   without is externally tagged, the union member's name being its key. A struct's unnamed union
//!   and a flattened named union are flattened into the struct.
//! - `$Json.base64` and `$Json.hex` select the `capnp_serde::Base64` and `capnp_serde::Hex`
//!   encodings of `Data`.
//!
//! A field of type `Json.Value` is a `serde_json::Value`.
//!
//! The attributes drive serde's derived `Serialize` impls. `Deserialize` impls are generated
//! instead, through `capnp_serde::Fields`: the generator computes every struct's and union's list
//! of JSON keys, including those flattened into it, so that the generated impls decode flattened
//! fields and union members straight from the input and pass keys on as indices.
//!
//! The `capnp_serde` crate documentation lists the known differences from the C++ codec.

