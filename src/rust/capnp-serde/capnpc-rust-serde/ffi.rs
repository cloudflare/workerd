//! Generates the cxx bridge of a schema file, through which C++ parses JSON into the generated
//! types and reads them in place, without copying them into a Cap'n Proto message.
//!
//! The API follows that of Cap'n Proto's C++ readers. Every struct, group and named union of the
//! file is an opaque Rust type, in the C++ namespace of the file's `$Cxx.namespace` followed by
//! `::serde`, so that the names do not clash with the classes `capnpc-c++` generates (or
//! `capnp_serde::<file>` without the annotation). For a struct `Foo`:
//!
//! - `parseFoo(rust::Slice<const uint8_t> json) -> rust::Box<Foo>` decodes a JSON document, and
//!   throws if it is not one of `Foo`. As in `JsonCodec::decode()`, the input ends at its first
//!   NUL byte, so it may be a `kj::String`'s array.
//! - `getX()` returns a `Bool` or number field's value, and an enum field's value as a shared
//!   enum of the bridge with the enum's name.
//! - `getX()` returns a `Text`, `Data` or `List` field as a `rust::Str` or a `rust::Slice` into
//!   the value, empty if the field is null; `hasX()` says whether it is.
//! - `getX()` returns a struct field as a reference, to a default value if the field is null;
//!   `hasX()` says whether it is. A group field is a reference to its group.
//! - A union has `which()`, which returns a shared enum `<Union>Which` of its members, `isX()`
//!   for each member, and `getX()` for each member that has a value, which returns the member's
//!   default if another member is set. A struct's unnamed union has these on the struct.
//!
//! Lists of structs are `rust::Slice<const T>`, and lists of `Text` are
//! `rust::Slice<const rust::String>`. The getters are inherent methods private to the generated
//! module, so the Rust types' own API is unchanged.
//!
//! C++ cannot read `Void` and `Json.Value` fields, lists of `Data`, enums and lists, and values
//! whose types other schema files declare; the bridge has a comment in place of each such
//! accessor.

