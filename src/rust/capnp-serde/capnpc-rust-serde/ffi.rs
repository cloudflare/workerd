/// `$Cxx.namespace`.
const CXX_NAMESPACE_ID: u64 = 0xb9c6_f99e_bf80_5f2c;

const SOME: &str = "::core::option::Option::Some";
const NONE: &str = "::core::option::Option::None";

/// The path of the bridge generated from the schema file at `filename`: `foo/bar-baz.capnp`
/// becomes `foo/bar_baz_serde_ffi.rs`.
pub fn output_path(filename: &str) -> String {
    let serde = super::output_path(filename);
    let stem = serde.strip_suffix(".rs").unwrap_or(&serde);
    format!("{stem}_ffi.rs")
}

/// Generates the bridge of the schema file `file`, named `filename`. `items` holds the names of
/// the items generated so far, which the `Which` enums of named unions must not clash with.
pub fn generate(
    generator: &Generator,
    file: u64,
    filename: &str,
    items: &mut HashSet<String>,
) -> Result<String> {
    let mut ffi = Ffi {
        generator,
        file,
        items,
        enums: Code::default(),
        decls: Code::default(),
        impls: Code::default(),
        defaults: BTreeSet::new(),
    };
    ffi.gen_scope(file)?;

    let mut out = Code::default();
    out.line(
        0,
        &format!("// Generated by capnpc-rust-serde from {filename}. DO NOT EDIT."),
    );
    out.blank();
    out.line(
        0,
        &format!(
            "//! The cxx bridge of the types of `{filename}`, through which C++ parses JSON into \
             them and reads them."
        ),
    );
    out.blank();
    out.line(0, "#![allow(unsafe_code, reason = \"cxx bridge\")]");
    out.blank();
    out.line(0, "use crate::*;");
    out.blank();
    out.line(
        0,
        &format!(
            "#[cxx::bridge(namespace = {:?})]",
            cxx_namespace(generator, file, filename)?
        ),
    );
    out.line(0, "pub mod ffi {");
    out.code.push_str(&ffi.enums.code);
    if !ffi.decls.code.is_empty() {
        out.line(1, "extern \"Rust\" {");
        out.code.push_str(&ffi.decls.code);
        out.line(1, "}");
    }
    out.line(0, "}");
    out.code.push_str(&ffi.impls.code);
    for name in &ffi.defaults {
        out.blank();
        out.line(0, &format!("impl {name} {{"));
        out.line(
            1,
            "/// The value of a null pointer to this type, which C++ reads as Cap'n Proto's \
             readers do.",
        );
        out.line(1, "fn ffi_default() -> &'static Self {");
        out.line(
            2,
            &format!(
                "static DEFAULT: ::std::sync::LazyLock<{name}> = \
                 ::std::sync::LazyLock::new(::core::default::Default::default);"
            ),
        );
        out.line(2, "&DEFAULT");
        out.line(1, "}");
        out.line(0, "}");
    }
    Ok(out.code)
}

/// The C++ namespace of the bridge of `file`.
fn cxx_namespace(generator: &Generator, file: u64, filename: &str) -> Result<String> {
    for annotation in generator.node(file)?.get_annotations()? {
        if annotation.get_id() == CXX_NAMESPACE_ID
            && let value::Text(text) = annotation.get_value()?.which()?
        {
            let namespace = text?.to_str()?.trim_start_matches("::").to_owned();
            return Ok(format!("{namespace}::serde"));
        }
    }
    let base = filename.rsplit('/').next().unwrap_or(filename);
    let stem = base.strip_suffix(".capnp").unwrap_or(base);
    Ok(format!("capnp_serde::{}", stem.replace('-', "_")))
}

/// Lines of generated code.
#[derive(Default)]
struct Code {
    code: String,
}

impl Code {
    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.code.push_str("    ");
        }
        self.code.push_str(text);
        self.code.push('\n');
    }

    fn blank(&mut self) {
        self.code.push('\n');
    }

    fn doc(&mut self, indent: usize, doc: Option<&str>) {
        for line in doc.unwrap_or_default().lines() {
            let line = line.trim_end();
            if line.is_empty() {
                self.line(indent, "///");
            } else {
                self.line(indent, &format!("/// {line}"));
            }
        }
    }
}

/// How C++ reads a value of a field or a union member.
enum Access {
    /// A copy of a `Bool` or a number of Rust type `ty`, or of an enum `ty` as the bridge's enum
    /// of the same name.
    Value { ty: String, bridge_enum: bool },
    /// A `Text`, as a `&str`.
    Str,
    /// `Data` or a list, as a slice of `bridge` elements, which are `rust` in Rust.
    Slice { bridge: String, rust: String },
    /// A struct or a group `name`, held in a `Box` if `boxed`.
    Struct { name: String, boxed: bool },
}

impl Access {
    fn borrows(&self) -> bool {
        !matches!(self, Self::Value { .. })
    }

    /// The return type of the getter in the bridge.
    fn bridge_type(&self) -> String {
        match self {
            Self::Value { ty, .. } => ty.clone(),
            Self::Str => "&'a str".to_owned(),
            Self::Slice { bridge, .. } => format!("&'a [{bridge}]"),
            Self::Struct { name, .. } => format!("&'a {name}"),
        }
    }

    /// The return type of the getter in Rust.
    fn rust_type(&self) -> String {
        match self {
            Self::Value {
                ty,
                bridge_enum: true,
            } => format!("ffi::{ty}"),
            Self::Value { ty, .. } => ty.clone(),
            Self::Str => "&str".to_owned(),
            Self::Slice { rust, .. } => format!("&[{rust}]"),
            Self::Struct { name, .. } => format!("&{name}"),
        }
    }

    /// The value of `place`, an expression of the value's Rust type, as the getter returns it.
    fn read_place(&self, place: &str) -> String {
        match self {
            Self::Value {
                ty,
                bridge_enum: true,
            } => format!("ffi::{ty} {{ repr: {place} as u16 }}"),
            Self::Value { .. } => place.to_owned(),
            Self::Str => format!("{place}.as_str()"),
            Self::Slice { .. } => format!("{place}.as_slice()"),
            Self::Struct { boxed: true, .. } => format!("&*{place}"),
            Self::Struct { boxed: false, .. } => format!("&{place}"),
        }
    }

    /// The value that `reference`, a variable that refers to the value, refers to, as the getter
    /// returns it.
    fn read_ref(&self, reference: &str) -> String {
        match self {
            Self::Value { .. } => self.read_place(&format!("*{reference}")),
            Self::Str | Self::Slice { .. } => self.read_place(reference),
            Self::Struct { boxed: true, .. } => format!("&**{reference}"),
            Self::Struct { boxed: false, .. } => reference.to_owned(),
        }
    }
}

/// Why C++ cannot read a value.
type Unsupported = String;

/// The shape of a union member's variant (see `Generator::gen_union_member`).
enum Shape {
    /// `Variant(value)`.
    Tuple,
    /// `Variant { value }`.
    Named,
    /// `Variant`.
    Unit,
}

/// A union whose accessors are methods of `owner`, which reads the union's enum `ty` from
/// `scrutinee`. `which` is the bridge's enum of its members.
struct Union<'r> {
    owner: &'r str,
    scrutinee: &'r str,
    ty: &'r str,
    which: &'r str,
}

/// A union member's variant.
struct UnionMember {
    variant: String,
    shape: Shape,
    /// How C++ reads the member's value, or `None` for a `Void`.
    access: Option<Result<Access, Unsupported>>,
    /// The Rust expression of the member's schema default, if its value is a `Bool`, a number or
    /// an enum.
    default: Option<String>,
}

struct Ffi<'g, 'a, 'i> {
    generator: &'g Generator<'a>,
    file: u64,
    items: &'i mut HashSet<String>,
    /// The bridge's shared enums.
    enums: Code,
    /// The declarations of its `extern "Rust"` block.
    decls: Code,
    /// The getters and parse functions that the bridge calls.
    impls: Code,
    /// The structs whose `ffi_default()` the getters call.
    defaults: BTreeSet<String>,
}

impl Ffi<'_, '_, '_> {
    /// Generates the bridge items of the types nested in `scope`.
    fn gen_scope(&mut self, scope: u64) -> Result<()> {
        for nested in self.generator.node(scope)?.get_nested_nodes()? {
            let id = nested.get_id();
            let Ok(child) = self.generator.node(id) else {
                continue;
            };
            match child.which()? {
                // Generic structs and what they declare have no Rust types.
                node::Struct(_) if child.get_is_generic() => {}
                node::Struct(_) => self.gen_struct(id, None)?,
                node::Enum(_) => self.gen_enum(id)?,
                node::Interface(_) => self.gen_scope(id)?,
                node::File(()) | node::Const(_) | node::Annotation(_) => {}
            }
        }
        Ok(())
    }

    /// The file that declares node `id`.
    fn file_of(&self, mut id: u64) -> Result<u64> {
        loop {
            let node = self.generator.node(id)?;
            if matches!(node.which()?, node::File(())) {
                return Ok(id);
            }
            id = node.get_scope_id();
        }
    }

    fn in_file(&self, id: u64) -> Result<bool> {
        Ok(self.file_of(id)? == self.file)
    }

    fn gen_enum(&mut self, id: u64) -> Result<()> {
        let node::Enum(en) = self.generator.node(id)?.which()? else {
            bail!("not an enum");
        };
        let name = self.generator.name(id)?.to_owned();
        let variants: Vec<String> = en
            .get_enumerants()?
            .iter()
            .map(|enumerant| Ok(identifier(&pascal_case(enumerant.get_name()?.to_str()?))))
            .collect::<Result<_>>()?;
        self.enums.doc(1, self.generator.doc(id).as_deref());
        self.gen_shared_enum(&name, &variants);
        self.gen_scope(id)
    }

    /// Generates the shared enum `name` of the bridge, whose variants are `variants` in ordinal
    /// order.
    fn gen_shared_enum(&mut self, name: &str, variants: &[String]) {
        self.enums.line(1, "#[repr(u16)]");
        self.enums.line(1, &format!("enum {name} {{"));
        for (ordinal, variant) in variants.iter().enumerate() {
            self.enums.line(2, &format!("{variant} = {ordinal},"));
        }
        self.enums.line(1, "}");
        self.enums.blank();
    }

    /// Generates the bridge items of struct or group `id`, whose group field, if it is a group,
    /// says `context` about it.
    fn gen_struct(&mut self, id: u64, context: Option<&GroupContext>) -> Result<()> {
        let generator = self.generator;
        let node = generator.node(id)?;
        let name = generator.name(id)?.to_owned();
        let fields = generator.fields(id)?;
        let (union_fields, plain_fields): (Vec<&Field>, Vec<&Field>) =
            fields.iter().partition(|field| field.is_union_member());

        let doc = match context {
            Some(context) => context.doc.clone(),
            None => generator.doc(id),
        };
        self.decls.doc(2, doc.as_deref());
        self.decls.line(2, &format!("type {name};"));
        self.impls.blank();
        self.impls.line(0, &format!("impl {name} {{"));
        for field in &plain_fields {
            self.gen_field(&name, id, field)?;
        }
        if !union_fields.is_empty() {
            let tagging = Generator::union_tagging(node, context)?;
            let union_name = format!("{name}Which");
            // The union's enum is not in the bridge, which names its `Which` enum the same.
            self.enums.line(
                1,
                &format!("/// Which member of the unnamed union of `{name}` is set."),
            );
            let union = Union {
                owner: &name,
                scrutinee: "&self.which",
                ty: &union_name,
                which: &union_name,
            };
            self.gen_union(&union, id, &union_fields, &tagging)?;
        }
        self.impls.line(0, "}");
        if context.is_none() {
            self.gen_parse(&name);
        }
        self.decls.blank();

        self.gen_groups(&fields)?;
        self.gen_scope(id)
    }

    /// Generates the bridge items of the groups among `fields`.
    fn gen_groups(&mut self, fields: &[Field]) -> Result<()> {
        let generator = self.generator;
        for field in fields {
            let field::Group(group) = field.reader.which()? else {
                continue;
            };
            let id = group.get_type_id();
            let context = GroupContext::new(field);
            if !generator.is_named_union(id, field)? {
                self.gen_struct(id, Some(&context))?;
                continue;
            }
            // A named union is its enum.
            let name = generator.name(id)?.to_owned();
            let which = format!("{name}Which");
            if !self.items.insert(which.clone()) {
                bail!("more than one item would be named `{which}`");
            }
            let members = generator.fields(id)?;
            let member_refs: Vec<&Field> = members.iter().collect();
            let tagging = Generator::union_tagging(generator.node(id)?, Some(&context))?;
            self.decls.doc(2, context.doc.as_deref());
            self.decls.line(2, &format!("type {name};"));
            self.impls.blank();
            self.impls.line(0, &format!("impl {name} {{"));
            self.enums
                .line(1, &format!("/// Which member of `{name}` is set."));
            let union = Union {
                owner: &name,
                scrutinee: "self",
                ty: &name,
                which: &which,
            };
            self.gen_union(&union, id, &member_refs, &tagging)?;
            self.impls.line(0, "}");
            self.decls.blank();
            self.gen_groups(&members)?;
        }
        Ok(())
    }

    /// Generates `parseName()`.
    fn gen_parse(&mut self, name: &str) {
        let rust = format!("parse_{}", snake_case(name));
        self.decls.line(
            2,
            &format!(
                "/// Decodes a JSON document of `{name}`, as `capnp::JsonCodec::decode()` with \
                 `handleByAnnotation()` does. Like it, takes the input to end at its first NUL."
            ),
        );
        self.decls
            .line(2, &format!("#[cxx_name = \"parse{}\"]", pascal_case(name)));
        self.decls.line(
            2,
            &format!("fn {rust}(json: &[u8]) -> Result<Box<{name}>>;"),
        );
        self.impls.blank();
        self.impls.line(
            0,
            &format!(
                "fn {rust}(json: &[u8]) -> ::serde_json::Result<::std::boxed::Box<{name}>> {{"
            ),
        );
        self.impls.line(1, "::capnp_serde::from_codec_input(json)");
        self.impls.line(0, "}");
    }

    /// Declares and defines the getter `getX()` of `owner` for the field or member `field`,
    /// whose body is `body` and which returns `access`.
    fn gen_getter(
        &mut self,
        owner: &str,
        prefix: &str,
        field: &Field,
        access: &Access,
        body: &[String],
    ) {
        let rust = format!("{prefix}_{}", snake_case(&field.name));
        let cxx = format!("{prefix}{}", pascal_case(&field.name));
        self.decls.doc(2, field.doc.as_deref());
        self.decls.line(2, &format!("#[cxx_name = \"{cxx}\"]"));
        if access.borrows() {
            // cxx requires explicit lifetimes of extern "Rust" functions to be unsafe.
            self.decls.line(
                2,
                &format!(
                    "unsafe fn {rust}<'a>(self: &'a {owner}) -> {};",
                    access.bridge_type()
                ),
            );
        } else {
            self.decls.line(
                2,
                &format!("fn {rust}(self: &{owner}) -> {};", access.bridge_type()),
            );
        }
        self.impls
            .line(1, &format!("fn {rust}(&self) -> {} {{", access.rust_type()));
        for line in body {
            self.impls.line(2, line);
        }
        self.impls.line(1, "}");
    }

    /// Declares and defines `predicate()` of `owner`, which returns `body`.
    fn gen_predicate(&mut self, owner: &str, prefix: &str, field: &Field, body: &str) {
        let rust = format!("{prefix}_{}", snake_case(&field.name));
        let cxx = format!("{prefix}{}", pascal_case(&field.name));
        self.decls.line(2, &format!("#[cxx_name = \"{cxx}\"]"));
        self.decls
            .line(2, &format!("fn {rust}(self: &{owner}) -> bool;"));
        self.impls.line(1, &format!("fn {rust}(&self) -> bool {{"));
        self.impls.line(2, body);
        self.impls.line(1, "}");
    }

    fn unsupported(&mut self, field: &Field, why: &str) {
        self.decls
            .line(2, &format!("// No accessors for `{}`: {why}.", field.name));
    }

    /// Generates the accessors of `field`, a field of struct or group `scope`, whose Rust type is
    /// `owner`.
    fn gen_field(&mut self, owner: &str, scope: u64, field: &Field) -> Result<()> {
        let ident = identifier(&snake_case(&field.name));
        let slot = match field.reader.which()? {
            field::Group(group) => {
                let access = Access::Struct {
                    name: self.generator.name(group.get_type_id())?.to_owned(),
                    boxed: false,
                };
                let body = access.read_place(&format!("self.{ident}"));
                self.gen_getter(owner, "get", field, &access, &[body]);
                return Ok(());
            }
            field::Slot(slot) => slot,
        };
        let ty = slot.get_type()?;
        if matches!(ty.which()?, type_::Void(())) {
            return Ok(());
        }
        let access = match self.access(scope, field, ty)? {
            Ok(access) => access,
            Err(why) => {
                self.unsupported(field, &why);
                return Ok(());
            }
        };
        if let Access::Value { .. } = access {
            let body = access.read_place(&format!("self.{ident}"));
            self.gen_getter(owner, "get", field, &access, &[body]);
            return Ok(());
        }
        let absent = self.absent(&access);
        let body = [
            format!("match &self.{ident} {{"),
            format!("    {SOME}(value) => {},", access.read_ref("value")),
            format!("    {NONE} => {absent},"),
            "}".to_owned(),
        ];
        self.gen_getter(owner, "get", field, &access, &body);
        self.gen_predicate(
            owner,
            "has",
            field,
            &format!("::core::option::Option::is_some(&self.{ident})"),
        );
        Ok(())
    }

    /// The value a getter returns for a null pointer of `access`.
    fn absent(&mut self, access: &Access) -> String {
        match access {
            Access::Value { .. } => unreachable!("values are not pointers"),
            Access::Str => "\"\"".to_owned(),
            Access::Slice { .. } => "&[]".to_owned(),
            Access::Struct { name, .. } => {
                self.defaults.insert(name.clone());
                format!("{name}::ffi_default()")
            }
        }
    }

    /// How C++ reads a value of type `ty`, the type of `field` of `scope`.
    fn access(
        &self,
        scope: u64,
        field: &Field,
        ty: type_::Reader,
    ) -> Result<Result<Access, Unsupported>> {
        let value = |ty: &str| {
            Ok(Ok(Access::Value {
                ty: ty.to_owned(),
                bridge_enum: false,
            }))
        };
        match ty.which()? {
            type_::Void(()) => Ok(Err("a Void has no value".to_owned())),
            type_::Bool(()) => value("bool"),
            type_::Int8(()) => value("i8"),
            type_::Int16(()) => value("i16"),
            type_::Int32(()) => value("i32"),
            type_::Int64(()) => value("i64"),
            type_::Uint8(()) => value("u8"),
            type_::Uint16(()) => value("u16"),
            type_::Uint32(()) => value("u32"),
            type_::Uint64(()) => value("u64"),
            type_::Float32(()) => value("f32"),
            type_::Float64(()) => value("f64"),
            type_::Enum(en) => {
                let id = en.get_type_id();
                if !self.in_file(id)? {
                    return Ok(Err("its enum is declared in another file".to_owned()));
                }
                Ok(Ok(Access::Value {
                    ty: self.generator.name(id)?.to_owned(),
                    bridge_enum: true,
                }))
            }
            type_::Text(()) => Ok(Ok(Access::Str)),
            type_::Data(()) => Ok(Ok(Access::Slice {
                bridge: "u8".to_owned(),
                rust: "u8".to_owned(),
            })),
            type_::List(list) => {
                let element = list.get_element_type()?;
                let (bridge, rust) = match element.which()? {
                    type_::Bool(()) => ("bool", "bool"),
                    type_::Int8(()) => ("i8", "i8"),
                    type_::Int16(()) => ("i16", "i16"),
                    type_::Int32(()) => ("i32", "i32"),
                    type_::Int64(()) => ("i64", "i64"),
                    type_::Uint8(()) => ("u8", "u8"),
                    type_::Uint16(()) => ("u16", "u16"),
                    type_::Uint32(()) => ("u32", "u32"),
                    type_::Uint64(()) => ("u64", "u64"),
                    type_::Float32(()) => ("f32", "f32"),
                    type_::Float64(()) => ("f64", "f64"),
                    type_::Text(()) => ("String", "::std::string::String"),
                    type_::Struct(st) => match self.struct_access(st.get_type_id())? {
                        Ok(name) => {
                            return Ok(Ok(Access::Slice {
                                bridge: name.clone(),
                                rust: name,
                            }));
                        }
                        Err(why) => return Ok(Err(format!("its elements: {why}"))),
                    },
                    _ => {
                        return Ok(Err(
                            "C++ reads lists of Bool, numbers, Text and structs only".to_owned(),
                        ));
                    }
                };
                Ok(Ok(Access::Slice {
                    bridge: bridge.to_owned(),
                    rust: rust.to_owned(),
                }))
            }
            type_::Struct(st) => match self.struct_access(st.get_type_id())? {
                Ok(name) => Ok(Ok(Access::Struct {
                    name,
                    boxed: self.generator.field_type(scope, field, ty)?.boxed,
                })),
                Err(why) => Ok(Err(why)),
            },
            type_::Interface(_) | type_::AnyPointer(_) => {
                Ok(Err("it has no JSON representation".to_owned()))
            }
        }
    }

    /// The bridge's name of struct `id`, if it has the struct.
    fn struct_access(&self, id: u64) -> Result<Result<String, Unsupported>> {
        if id == JSON_VALUE_ID {
            return Ok(Err("C++ does not read Json.Value".to_owned()));
        }
        if !self.in_file(id)? {
            return Ok(Err(format!(
                "{} is declared in another file",
                self.generator.display_name(id)
            )));
        }
        Ok(Ok(self.generator.name(id)?.to_owned()))
    }

    /// Generates the accessors of `union`, whose members are `members`, fields of `scope`. The
    /// caller has written the doc comment of the union's `Which` enum.
    fn gen_union(
        &mut self,
        union: &Union,
        scope: u64,
        members: &[&Field],
        tagging: &Tagging,
    ) -> Result<()> {
        let Union {
            owner,
            scrutinee,
            ty: union_ty,
            which,
        } = *union;
        let mut variants = Vec::new();
        let mut which_arms = Vec::new();
        let mut getters = Vec::new();
        for member in members {
            let UnionMember {
                variant,
                shape,
                access,
                default,
            } = self.union_member(scope, member, tagging)?;
            let path = format!("{union_ty}::{variant}");
            let any = match shape {
                Shape::Tuple => format!("{path}(..)"),
                Shape::Named => format!("{path} {{ .. }}"),
                Shape::Unit => path.clone(),
            };
            let ordinal = member.reader.get_discriminant_value();
            which_arms.push(format!("    {any} => ffi::{which}::{variant},"));
            variants.push((usize::from(ordinal), variant));
            getters.push((member, path, any, shape, access, default));
        }
        variants.sort();
        let variants: Vec<String> = variants.into_iter().map(|(_, variant)| variant).collect();
        self.gen_shared_enum(which, &variants);

        self.decls.line(2, "#[cxx_name = \"which\"]");
        self.decls
            .line(2, &format!("fn which(self: &{owner}) -> {which};"));
        self.impls
            .line(1, &format!("fn which(&self) -> ffi::{which} {{"));
        self.impls.line(2, &format!("match {scrutinee} {{"));
        for arm in &which_arms {
            self.impls.line(2, arm);
        }
        self.impls.line(2, "}");
        self.impls.line(1, "}");

        for (member, path, any, shape, access, default) in getters {
            self.gen_predicate(
                owner,
                "is",
                member,
                &format!("::core::matches!({scrutinee}, {any})"),
            );
            let access = match access {
                None => continue,
                Some(Ok(access)) => access,
                Some(Err(why)) => {
                    self.unsupported(member, &why);
                    continue;
                }
            };
            let pattern = match shape {
                Shape::Tuple => format!("{path}(value)"),
                Shape::Named => format!("{path} {{ value }}"),
                Shape::Unit => continue,
            };
            let default = match default {
                Some(default) => access.read_place(&default),
                None => self.absent(&access),
            };
            let body = [
                format!("match {scrutinee} {{"),
                format!("    {pattern} => {},", access.read_ref("value")),
                format!("    _ => {default},"),
                "}".to_owned(),
            ];
            self.gen_getter(owner, "get", member, &access, &body);
        }
        Ok(())
    }

    /// The variant of union member `member`, a field of `scope`, as `Generator::gen_union_member`
    /// generates it.
    fn union_member(&self, scope: u64, member: &Field, tagging: &Tagging) -> Result<UnionMember> {
        let generator = self.generator;
        let variant = identifier(&pascal_case(&member.name));
        let flattened = member.flatten()?.is_some();
        let (rust_type, access, default) = match member.reader.which()? {
            field::Group(group) => {
                let id = group.get_type_id();
                let name = generator.name(id)?.to_owned();
                let mut rust_type = RustType::new(&name, None, Kind::Pointer);
                rust_type.struct_id = Some(id);
                let rust_type = generator.boxed(scope, rust_type)?;
                let boxed = rust_type.boxed;
                (rust_type, Some(Ok(Access::Struct { name, boxed })), None)
            }
            field::Slot(slot) => {
                let ty = slot.get_type()?;
                let rust_type = generator.field_type(scope, member, ty)?;
                let access = if rust_type.kind == Kind::Void {
                    None
                } else {
                    Some(self.access(scope, member, ty)?)
                };
                let default = if rust_type.kind == Kind::Primitive {
                    Some(
                        generator
                            .primitive_default(ty, slot.get_default_value()?)?
                            .0,
                    )
                } else {
                    None
                };
                (rust_type, access, default)
            }
        };
        let shape = if tagging.tag.is_none() || (flattened && rust_type.struct_id.is_some()) {
            Shape::Tuple
        } else if rust_type.kind == Kind::Void {
            Shape::Unit
        } else {
            Shape::Named
        };
        Ok(UnionMember {
            variant,
            shape,
            access,
            default,
        })
    }
}
